// Keeps paid files off the public web. Netlify publishes the repo root, so any
// file in content/library/ is downloadable by anyone who knows its address.
// This script rewrites the block of forced-404 redirects in netlify.toml (one
// per paid PDF in content/pricing.json, plus the function source and the
// server-only library content, quest definitions). Paid files are then reachable only through the
// download function, after a purchase. Run: node scripts/block-paid-files.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const pricing = JSON.parse(fs.readFileSync(path.join(root, 'content', 'pricing.json'), 'utf8'));
const START = '# >>> paid-files-blocked (generated by scripts/block-paid-files.mjs; do not edit by hand)';
const END = '# <<< paid-files-blocked';

export function paidPdfFiles(p = pricing) {
  const files = new Set();
  for (const list of ['products', 'blueprint_series', 'partner_ip', 'bonus_products', 'memberships']) {
    for (const item of p[list] || []) if (item.pdf_file) files.add(item.pdf_file);
  }
  return [...files].sort();
}

export function blockedPaths(p = pricing) {
  return [...paidPdfFiles(p).map((f) => `/content/library/${f}`), '/content/library.json', '/content/quests/*', '/content/ip-backlog.json', '/netlify/*'];
}

const rule = (from) => `[[redirects]]\n  from = "${from}"\n  to = "/404"\n  status = 404\n  force = true\n`;

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const tomlPath = path.join(root, 'netlify.toml');
  let toml = fs.readFileSync(tomlPath, 'utf8');
  // drop the earlier hand-written single rule and any previous generated block
  toml = toml.replace(/\n# Paid file: delivered only by the download function after a purchase\.\n\[\[redirects\]\]\n  from = "\/content\/library\/creator-website-blueprint\.pdf"\n  to = "\/404"\n  status = 404\n  force = true\n/, '\n');
  toml = toml.replace(new RegExp(`\\n?${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}\\n?`), '\n');
  const block = `\n${START}\n${blockedPaths().map(rule).join('\n')}${END}\n`;
  toml = toml.replace(/\s*$/, '\n') + block;
  fs.writeFileSync(tomlPath, toml);
  console.log(`blocked ${blockedPaths().length} paths`);
}
